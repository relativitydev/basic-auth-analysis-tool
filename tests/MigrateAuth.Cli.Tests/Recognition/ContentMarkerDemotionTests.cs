using System.Collections.Frozen;
using System.Collections.Immutable;
using System.Text.RegularExpressions;

using MigrateAuth.Cli.Catalog;
using MigrateAuth.Cli.Emission;
using MigrateAuth.Cli.Lexical;
using MigrateAuth.Cli.Reading;
using MigrateAuth.Cli.Recognition;

using MigrateAuth.Cli.Tests.Fixtures;

using Xunit;

namespace MigrateAuth.Cli.Tests.Recognition;

/// <summary>
/// <see cref="ContentMarker"/>, the demotion signal the engine
/// evaluates over a file's decoded text rather than its name or its folder segments.
///
/// Cases that the <c>ExemplarOne</c> fixture analyzer's own two declared markers can
/// exercise go through <see cref="RecognitionHarness"/>, exactly as
/// <see cref="ExemplarFixtureAnalyzer"/> declares them. Cases that need a marker the shipped
/// catalog does not declare - a catastrophic pattern - go through <see cref="DemotionSignalProbe"/>,
/// on <see cref="MatchBoundTests"/>'s own precedent.
/// </summary>
public sealed class ContentMarkerDemotionTests
{
	private const string _CREDENTIAL_TYPE_PATTERN_CLASS = "EXM-001";

	private const string _GENERATED_HEADER_LINE = "-- generated by the exemplar generator";
	private const string _CREDENTIAL_CONSTRUCTION_LINE =
		"let credentials = NewExemplarCredentials(operatorName, \"hunter2\")";

	private const string _PATH_CARRYING_THE_MARKERS_WORDS =
		"src/generated-by-the-exemplar-generator/module.ex1";

	private const string _CODE_ONLY_MARKER_IN_A_COMMENT = "-- ExemplarTestMarker";
	private const string _CODE_ONLY_MARKER_IN_A_STRING_LITERAL = "let s = \"ExemplarTestMarker\"";
	private const string _CODE_ONLY_MARKER_IN_CODE = "let ExemplarTestMarker = true";

	private const string _CATASTROPHIC_CONTENT_PATTERN = @"^(\w+\s?)*$";
	private const string _BENIGN_FIRING_PATTERN = @"\bfox\b";
	private const string _INPUT_THAT_CANNOT_MATCH =
		"the quick brown fox jumps over the lazy dog and keeps running well past the point of reason!";
	private const string _CATASTROPHIC_PROBE_RELATIVE_PATH = "source/pathological.ex1";

	private static readonly TimeSpan _anExpressionLevelTimeout = TimeSpan.FromMilliseconds(1);

	private const string _REFERENCE_LANGUAGE_NAME = "ExemplarOne";
	private const int _EXPECTED_REFERENCE_CONTENT_MARKER_COUNT = 2;

	/// <summary>
	/// A content marker fires on the file's TEXT, and it fires even though
	/// the text it matched sits entirely inside a <see cref="LexicalZone.Comment"/> - the shipped
	/// marker's own shape, since a generated-code header opens with the language's own line-comment
	/// token. <see cref="ContentMarkerZone.AnyZone"/> exists exactly so that does not block it.
	/// </summary>
	[Fact]
	public void AnAnyZoneContentMarkerFiresOnTextInsideACommentAndDemotesTheConstruct()
	{
		string source = _GENERATED_HEADER_LINE + "\n" + _CREDENTIAL_CONSTRUCTION_LINE;
		RecognitionHarness harness = new();

		Assert.Equal(LexicalZone.Comment, harness.ContextFor(source).Mask.ZoneAt(0));

		ImmutableArray<RecognizedConstruct> recognized = harness.Recognize(source);
		RecognizedConstruct construct = Assert.Single(recognized);

		Assert.Equal(_CREDENTIAL_TYPE_PATTERN_CLASS, construct.PatternClassIdentifier);
		Assert.Equal(ConfidenceLevel.Low, construct.Level);
	}

	/// <summary>
	/// A content marker reads only <see cref="FileRecognitionContext.NormalizedText"/>,
	/// never the path - so a folder carrying the marker's own words, with content that does not,
	/// must not demote. Proves the split holds in the direction that matters for a false positive.
	/// </summary>
	[Fact]
	public void AContentMarkerNeverFiresFromAPathCarryingItsWords()
	{
		RecognitionHarness harness = new();

		ImmutableArray<RecognizedConstruct> recognized =
			harness.Recognize(_CREDENTIAL_CONSTRUCTION_LINE, _PATH_CARRYING_THE_MARKERS_WORDS);

		RecognizedConstruct construct = Assert.Single(recognized);
		Assert.Equal(ConfidenceLevel.High, construct.Level);
	}

	/// <summary>
	/// The shipped <see cref="ContentMarkerZone.CodeOnly"/> marker must not fire from a
	/// comment or a string literal, and must fire from code - the distinction
	/// <see cref="ContentMarkerZone.AnyZone"/> does not make.
	/// </summary>
	[Theory]
	[InlineData(_CODE_ONLY_MARKER_IN_A_COMMENT, ConfidenceLevel.High)]
	[InlineData(_CODE_ONLY_MARKER_IN_A_STRING_LITERAL, ConfidenceLevel.High)]
	[InlineData(_CODE_ONLY_MARKER_IN_CODE, ConfidenceLevel.Medium)]
	public void ACodeOnlyContentMarkerFiresOnlyWhenItsTextSitsOnCode(string placementLine, ConfidenceLevel expectedLevel)
	{
		string source = placementLine + "\n" + _CREDENTIAL_CONSTRUCTION_LINE;
		RecognitionHarness harness = new();

		ImmutableArray<RecognizedConstruct> recognized = harness.Recognize(source);
		RecognizedConstruct construct = Assert.Single(recognized);

		Assert.Equal(expectedLevel, construct.Level);
	}

	/// <summary>
	/// A content marker's match-bound timeout is the platform's own
	/// <see cref="RegexMatchTimeoutException"/>, raised inside
	/// <see cref="RecognitionEngine"/>'s existing match-bound <c>try</c> and never allowed to
	/// escape - <see cref="MatchBoundTests"/>'s own proof, repeated here for a content marker
	/// rather than a detection rule.
	/// </summary>
	[Fact]
	public void ACatastrophicContentMarkerTripsTheMatchBoundAndLeaksNothingAboutTheFile()
	{
		LanguageShapedDemotionSignals demotionSignals = DemotionSignalsWith(BuildCatastrophicMarker());

		(ImmutableArray<RecognizedConstruct> recognized, RecordingEmissionSink sink, string consoleText) =
			RecognizeUnderConsoleCapture(demotionSignals, _INPUT_THAT_CANNOT_MATCH, _CATASTROPHIC_PROBE_RELATIVE_PATH);

		EmittedFact skip = Assert.Single(sink.Received, fact => fact.Category is EmissionCategory.SkippedItem);
		Assert.Empty(recognized);
		Assert.Equal(SkippedItemCategory.MatchBoundExceeded, skip.SkippedItem);
		AssertNothingAboutTheTimeoutEscaped(sink, consoleText);
	}

	/// <summary>
	/// The no-short-circuit rule, proved rather than assumed: a marker that already
	/// fired is declared BEFORE the catastrophic one, and the file is still stopped under the match
	/// bound. A short-circuiting implementation would never reach the second marker and this file
	/// would complete normally instead.
	/// </summary>
	[Fact]
	public void AFiringMarkerDeclaredBeforeACatastrophicOneStillLetsTheCatastrophicOneTripTheBound()
	{
		ContentMarker firingMarker = new()
		{
			Expression = new Regex(_BENIGN_FIRING_PATTERN, RegexOptions.CultureInvariant, RecognitionEnginePolicy.MATCH_BOUND),
			Zone = ContentMarkerZone.AnyZone,
			Kind = DemotionKind.Generated
		};
		LanguageShapedDemotionSignals demotionSignals = DemotionSignalsWith(firingMarker, BuildCatastrophicMarker());

		(ImmutableArray<RecognizedConstruct> recognized, RecordingEmissionSink sink, string consoleText) =
			RecognizeUnderConsoleCapture(demotionSignals, _INPUT_THAT_CANNOT_MATCH, _CATASTROPHIC_PROBE_RELATIVE_PATH);

		EmittedFact skip = Assert.Single(sink.Received, fact => fact.Category is EmissionCategory.SkippedItem);
		Assert.Empty(recognized);
		Assert.Equal(SkippedItemCategory.MatchBoundExceeded, skip.SkippedItem);
		AssertNothingAboutTheTimeoutEscaped(sink, consoleText);
	}

	/// <summary>Every marker the shipped reference catalog declares ships with the bound.</summary>
	[Fact]
	public void EveryExemplarContentMarkerDeclaresTheMatchBoundTimeoutAndAZone()
	{
		ILanguageAnalyzer analyzer =
			ExemplarFixtureCatalog.Build().AnalyzersByLanguageName[_REFERENCE_LANGUAGE_NAME];
		ImmutableArray<ContentMarker> markers = analyzer.DemotionSignals.ContentMarkers;

		Assert.Equal(_EXPECTED_REFERENCE_CONTENT_MARKER_COUNT, markers.Length);
		Assert.All(markers, marker => Assert.Equal(RecognitionEnginePolicy.MATCH_BOUND, marker.Expression.MatchTimeout));
		Assert.Contains(markers, marker => marker.Zone is ContentMarkerZone.AnyZone);
		Assert.Contains(markers, marker => marker.Zone is ContentMarkerZone.CodeOnly);
	}

	private static (ImmutableArray<RecognizedConstruct> Recognized, RecordingEmissionSink Sink, string ConsoleText)
		RecognizeUnderConsoleCapture(LanguageShapedDemotionSignals demotionSignals, string sourceText, string relativePath)
	{
		ILanguageAnalyzer analyzer = DemotionSignalProbe.BuildAnalyzer(demotionSignals);
		RecordingEmissionSink sink = new();
		EmissionPoint emissionPoint = new([sink]);
		RecognitionEngine engine = new(emissionPoint);
		FileRecognitionContext context = DemotionSignalProbe.ContextFor(analyzer, emissionPoint, sourceText, relativePath);

		StringWriter capturedOutput = new();
		StringWriter capturedError = new();
		TextWriter previousOutput = Console.Out;
		TextWriter previousError = Console.Error;
		ImmutableArray<RecognizedConstruct> recognized;

		try
		{
			Console.SetOut(capturedOutput);
			Console.SetError(capturedError);

			recognized = engine.Recognize(context).Constructs;
		}
		finally
		{
			Console.SetOut(previousOutput);
			Console.SetError(previousError);
		}

		return (recognized, sink, string.Concat(capturedOutput.ToString(), capturedError.ToString()));
	}

	private static void AssertNothingAboutTheTimeoutEscaped(RecordingEmissionSink sink, string consoleText)
	{
		Assert.DoesNotContain(nameof(RegexMatchTimeoutException), consoleText, StringComparison.OrdinalIgnoreCase);
		Assert.DoesNotContain(nameof(TimeoutException), consoleText, StringComparison.OrdinalIgnoreCase);
		Assert.All(sink.Received, fact => Assert.False(fact.Rule.IsDeclared));
	}

	private static LanguageShapedDemotionSignals DemotionSignalsWith(params ContentMarker[] markers)
	{
		return new LanguageShapedDemotionSignals
		{
			FileNameSignals = FrozenSet<FileNameSignal>.Empty,
			FolderNameSignals = FrozenSet<FolderNameSignal>.Empty,
			GenerationMarkerExpressions = [],
			ContentMarkers = [.. markers]
		};
	}

	private static ContentMarker BuildCatastrophicMarker()
	{
		return new ContentMarker
		{
			Expression = new Regex(_CATASTROPHIC_CONTENT_PATTERN, RegexOptions.CultureInvariant, _anExpressionLevelTimeout),
			Zone = ContentMarkerZone.AnyZone,
			Kind = DemotionKind.Generated
		};
	}
}
