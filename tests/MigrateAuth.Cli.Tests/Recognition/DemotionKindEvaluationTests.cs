using System.Collections.Frozen;
using System.Text.RegularExpressions;

using MigrateAuth.Cli.Catalog;
using MigrateAuth.Cli.Emission;
using MigrateAuth.Cli.Recognition;

using Xunit;

namespace MigrateAuth.Cli.Tests.Recognition;

/// <summary>
/// DEMOTION KINDS, EVALUATED WITH NO SHORT CIRCUIT AND COMPOSED BY KIND.
///
/// Every case goes through the real <see cref="RecognitionEngine"/> over the real Exemplar grammar via
/// <see cref="DemotionSignalProbe"/>, with only the declared demotion signals replaced. The same High
/// construct sits in every file, so each level read measures the kinds that fired and nothing else.
/// </summary>
public sealed class DemotionKindEvaluationTests
{
	private const string _CREDENTIAL_CONSTRUCTION_IN_CODE = """
		let credentials = NewExemplarCredentials(operatorName, "hunter2")
		""";

	private const LowConfidenceReasons _RESERVED_GENERAL_REASON_BIT = (LowConfidenceReasons)4;
	private const string _TEST_SUFFIX = ".spec.ex1";
	private const string _MOCK_PREFIX = "fake-";
	private const string _GENERATED_FOLDER = "gen";
	private const string _VENDORED_FOLDER = "vendor";
	private const string _GENERATION_MARKER_PATTERN = "^generated-output$";
	private const string _SAMPLE_CONTENT_WORD = "SampleMarkerWord";

	private const string _TEST_MOCK_AND_GENERATED_PATH = "gen/fake-module.spec.ex1";
	private const string _GENERATION_MARKER_ONLY_PATH = "generated-output/module.ex1";
	private const string _TEST_ONLY_PATH = "source/module.spec.ex1";
	private const string _VENDORED_AND_TEST_PATH = "vendor/module.spec.ex1";

	[Fact]
	public void TestMockAndGeneratedAllFireOnOneFileAndTheFileIsLowWithBothLowReasonsAndMarkedAsTestCode()
	{
		RecognizedConstruct construct = RecognizeUnder(BuildSignals(reverseDeclaredOrder: false), _TEST_MOCK_AND_GENERATED_PATH);

		Assert.Equal(ConfidenceLevel.Low, construct.Level);
		Assert.Equal(LowConfidenceReasons.DemotedMockFile | LowConfidenceReasons.DemotedGeneratedFile, construct.LowReasons);
		Assert.True(construct.TestCode);
	}

	[Fact]
	public void TheKindsThatFireDoNotDependOnTheOrderTheSignalsAreDeclaredIn()
	{
		RecognizedConstruct inOrder = RecognizeUnder(BuildSignals(reverseDeclaredOrder: false), _TEST_MOCK_AND_GENERATED_PATH);
		RecognizedConstruct reversed = RecognizeUnder(BuildSignals(reverseDeclaredOrder: true), _TEST_MOCK_AND_GENERATED_PATH);

		Assert.Equal(inOrder.Level, reversed.Level);
		Assert.Equal(inOrder.LowReasons, reversed.LowReasons);
		Assert.Equal(inOrder.TestCode, reversed.TestCode);
	}

	/// <summary>
	/// A name signal that already fired must not stop a content marker of another kind from being read: the
	/// Test file name fires first and the Sample content marker still adds its reason.
	/// </summary>
	[Fact]
	public void AContentMarkerOfAnotherKindIsStillReadAfterANameSignalFired()
	{
		RecognizedConstruct construct = RecognizeUnder(
			BuildSignals(reverseDeclaredOrder: false),
			_TEST_ONLY_PATH,
			$"{_SAMPLE_CONTENT_WORD}\n{_CREDENTIAL_CONSTRUCTION_IN_CODE}");

		Assert.Equal(ConfidenceLevel.Low, construct.Level);
		Assert.Equal(LowConfidenceReasons.DemotedSampleFile, construct.LowReasons);
		Assert.True(construct.TestCode);
	}

	[Fact]
	public void ATestKindAloneIsMediumWithNoLowReasonAndMarkedAsTestCode()
	{
		RecognizedConstruct construct = RecognizeUnder(BuildSignals(reverseDeclaredOrder: false), _TEST_ONLY_PATH);

		Assert.Equal(ConfidenceLevel.Medium, construct.Level);
		Assert.Equal(LowConfidenceReasons.None, construct.LowReasons);
		Assert.True(construct.TestCode);
	}

	[Fact]
	public void TestBesideVendoredIsLowWithTheVendoredReasonOnlyAndStillMarkedAsTestCode()
	{
		RecognizedConstruct construct = RecognizeUnder(BuildSignals(reverseDeclaredOrder: false), _VENDORED_AND_TEST_PATH);

		Assert.Equal(ConfidenceLevel.Low, construct.Level);
		Assert.Equal(LowConfidenceReasons.DemotedVendoredFile, construct.LowReasons);
		Assert.True(construct.TestCode);
	}

	/// <summary>A generation marker declares no kind: it is Generated by the definition of its shape.</summary>
	[Fact]
	public void AGenerationMarkerFiringIsOfTheGeneratedKind()
	{
		RecognizedConstruct construct = RecognizeUnder(BuildSignals(reverseDeclaredOrder: false), _GENERATION_MARKER_ONLY_PATH);

		Assert.Equal(ConfidenceLevel.Low, construct.Level);
		Assert.Equal(LowConfidenceReasons.DemotedGeneratedFile, construct.LowReasons);
		Assert.False(construct.TestCode);
	}

	[Fact]
	public void NoCombinationOfKindsEverSetsTheReservedGeneralDemotedFileBit()
	{
		LanguageShapedDemotionSignals signals = BuildSignals(reverseDeclaredOrder: false);
		string[] paths =
		[
			_TEST_MOCK_AND_GENERATED_PATH,
			_GENERATION_MARKER_ONLY_PATH,
			_TEST_ONLY_PATH,
			_VENDORED_AND_TEST_PATH
		];

		Assert.All(
			paths,
			path => Assert.False(RecognizeUnder(signals, path).LowReasons.HasFlag(_RESERVED_GENERAL_REASON_BIT), path));
	}

	private static RecognizedConstruct RecognizeUnder(
		LanguageShapedDemotionSignals signals,
		string relativePath,
		string source = _CREDENTIAL_CONSTRUCTION_IN_CODE)
	{
		ILanguageAnalyzer analyzer = DemotionSignalProbe.BuildAnalyzer(signals);
		RecordingEmissionSink sink = new();
		EmissionPoint emissionPoint = new([sink]);
		RecognitionEngine engine = new(emissionPoint);
		FileRecognitionContext context = DemotionSignalProbe.ContextFor(analyzer, emissionPoint, source, relativePath);

		return Assert.Single(engine.Recognize(context).Constructs);
	}

	private static LanguageShapedDemotionSignals BuildSignals(bool reverseDeclaredOrder)
	{
		FileNameSignal[] fileNames =
		[
			new() { Match = FileNameMatch.Suffix, Text = _TEST_SUFFIX, Kind = DemotionKind.Test },
			new() { Match = FileNameMatch.Prefix, Text = _MOCK_PREFIX, Kind = DemotionKind.Mock }
		];
		FolderNameSignal[] folders =
		[
			new() { FolderName = _GENERATED_FOLDER, Kind = DemotionKind.Generated },
			new() { FolderName = _VENDORED_FOLDER, Kind = DemotionKind.Vendored }
		];
		ContentMarker[] contentMarkers =
		[
			new()
			{
				Expression = new Regex(_SAMPLE_CONTENT_WORD, RegexOptions.CultureInvariant, RecognitionEnginePolicy.MATCH_BOUND),
				Zone = ContentMarkerZone.AnyZone,
				Kind = DemotionKind.Sample
			}
		];

		return new LanguageShapedDemotionSignals
		{
			FileNameSignals = (reverseDeclaredOrder ? Enumerable.Reverse(fileNames) : fileNames.AsEnumerable()).ToFrozenSet(),
			FolderNameSignals = (reverseDeclaredOrder ? Enumerable.Reverse(folders) : folders.AsEnumerable()).ToFrozenSet(),
			GenerationMarkerExpressions =
			[
				new Regex(_GENERATION_MARKER_PATTERN, RegexOptions.CultureInvariant, RecognitionEnginePolicy.MATCH_BOUND)
			],
			ContentMarkers = [.. contentMarkers]
		};
	}
}
