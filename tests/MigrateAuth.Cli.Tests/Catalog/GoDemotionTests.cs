	}

	// ------------------------------------------------------------------------------------------
	// Helpers
	// ------------------------------------------------------------------------------------------

	private static RecognizedConstruct Recognize(string source, string relativePath = GoRecognitionHarness.UNDEMOTED_RELATIVE_PATH)
	{
		ImmutableArray<RecognizedConstruct> constructs = new GoRecognitionHarness().Recognize(source, relativePath);

		return constructs.Single(construct => construct.PatternClassIdentifier == _HIGH_CLASS);
	}

	private static string Repeat(string line, int times)
	{
		StringBuilder builder = new();

		for (int count = 0; count < times; count++)
		{
			builder.Append(line);
		}

		return builder.ToString();
	}
