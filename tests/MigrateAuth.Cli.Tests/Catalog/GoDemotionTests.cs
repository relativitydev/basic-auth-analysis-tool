	[Fact]
	public void TheGeneratedHeaderIsReadAfterAtMostFiftyBlankOrCommentLinesAndNotAfterFiftyOne()
	{
		string atTheBound = Repeat("// note\n", _COMMENT_LINES_AT_THE_HEADER_BOUND) + _GENERATED_HEADER + "package sample\n\n" + _HIGH_CONSTRUCT;
