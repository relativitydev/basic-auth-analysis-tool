	/// <summary>
	/// The validator reaches the template provider through the contract, once per declared
	/// pattern class. The double is here to record that it was called, which is the only way to
	/// see a consumption that produces no visible result when everything is well formed.
	/// </summary>
	[Fact]
	public void TheValidatorQueriesTheTemplateProviderThroughTheContractForEveryPatternClassAndFlow()
	{
		Mock<RecommendationTemplateProvider> templateProvider = BuildCompleteTemplateProvider();
		ILanguageAnalyzer analyzer = BuildProbeAnalyzer(templateProvider.Object);

		AnalyzerContractValidator.Validate(analyzer);

		templateProvider.Verify(provider => provider(_PATTERN_CLASS, CredentialFlow.ClientCredentials), Times.Once);
		templateProvider.Verify(provider => provider(_PATTERN_CLASS, CredentialFlow.AuthorizationCode), Times.Once);
		templateProvider.Verify(provider => provider(_UNDECLARED_PATTERN_CLASS, It.IsAny<CredentialFlow>()), Times.Never);
	}

