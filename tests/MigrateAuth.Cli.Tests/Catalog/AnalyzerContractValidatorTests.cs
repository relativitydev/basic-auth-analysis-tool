	private static DetectionRule BuildProbeRule(
		string anchorCaptureGroupName,
		string displayName,
		TimeSpan? matchTimeout = null)
	{
		DetectionRule rule = new()
		{
			Expression = new Regex(_DETECTION_PATTERN, RegexOptions.None, matchTimeout ?? RecognitionEnginePolicy.MATCH_BOUND),
			AnchorPosition = MatchAnchor.AtCaptureGroup(anchorCaptureGroupName),
			BaseLevel = ConfidenceLevel.Medium,
			SelfSufficiency = SelfSufficiency.RequiresCallPathToBeEstablished,
			SymbolicVerdictInterpretation = SymbolicVerdictInterpretation.NotSubjectToSymbolicResolution,
			DestinationCertainty = DestinationCertainty.Unknown,
			DisplayName = displayName
		};

		return rule;
	}

	private static CandidateSelectionAndRecommendation BuildProbeCandidateSelection(
		RecommendationTemplateProvider templateProvider,
		string? languageFallbackText = null,
		ImmutableArray<FlowSignal> flowSignals = default,
		string? authorizationCodeFallbackText = null)
	{
		Dictionary<CredentialFlow, string> fallbackTextByFlow = [];

		if (languageFallbackText is not null)
		{
			fallbackTextByFlow[CredentialFlow.ClientCredentials] = languageFallbackText;
		}

		if (authorizationCodeFallbackText is not null)
		{
			fallbackTextByFlow[CredentialFlow.AuthorizationCode] = authorizationCodeFallbackText;
		}

		CandidateSelectionAndRecommendation element = new()
		{
			PreselectionAnchors = new[] { new PreselectionAnchor { Text = _PRESELECTION_ANCHOR_TEXT } }.ToFrozenSet(),
			TemplateProvider = templateProvider,
			FlowSignals = flowSignals.IsDefault ? [] : flowSignals,
			LanguageFallbackTextByFlow = fallbackTextByFlow.Count == 0 ? null : fallbackTextByFlow.ToFrozenDictionary()
		};

		return element;
	}

	private static FrozenSet<SubsumptionRule> BuildProbeSubsumptionRelation(string subsumedPatternClassIdentifier)
	{
		FrozenSet<SubsumptionRule> relation = new[]
		{
